import { topPlaces } from "../src/places.js";

const today = new Date("2026-10-25T12:00:00Z");
const exp = (note, date, extra = {}) => ({ type: "expense", amount: 100, date, note, ...extra });

describe("частые места", () => {
  it("сначала самые частые, затем более свежие", () => {
    const list = [
      exp("Магнит", "2026-10-01"), exp("Магнит", "2026-10-10"), exp("Магнит", "2026-10-20"),
      exp("Аптека", "2026-10-05"), exp("Аптека", "2026-10-06"),
      exp("Кофейня", "2026-10-24"),
      exp("Пекарня", "2026-10-02"),
    ];
    expect(topPlaces(list, today)).toEqual(["Магнит", "Аптека", "Кофейня", "Пекарня"]);
  });

  it("регистр не важен, показывается последнее написание", () => {
    const list = [exp("магнит", "2026-10-01"), exp("Магнит", "2026-10-02")];
    expect(topPlaces(list, today)).toEqual(["Магнит"]);
  });

  it("пропускает пустые, слишком короткие и слишком длинные заметки, доходы и пример данных", () => {
    const list = [
      exp("", "2026-10-01"), exp("ab", "2026-10-01"), exp("12345", "2026-10-01"),
      exp("а".repeat(40), "2026-10-01"),
      { type: "income", amount: 1, date: "2026-10-01", note: "Зарплата" },
      exp("Пример", "2026-10-01", { sample: true }),
      exp("Хлеб", "2026-10-01"),
    ];
    expect(topPlaces(list, today)).toEqual(["Хлеб"]);
  });

  it("старые записи (больше четырёх месяцев) не учитываются", () => {
    expect(topPlaces([exp("Давнее", "2026-01-01")], today)).toEqual([]);
  });

  it("не больше шести мест", () => {
    const list = ["Один", "Два", "Три", "Четыре", "Пять", "Шесть", "Семь", "Восемь"].map((n) => exp(n, "2026-10-01"));
    expect(topPlaces(list, today)).toHaveLength(6);
  });
});
